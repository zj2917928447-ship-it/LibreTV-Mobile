export function getPublicPackCategory(pack: PublicLivePack): Exclude<PublicPackCategory, 'all'> {
  if (pack.category) return pack.category;
  if (/builtin|zho|cn|tw|hk|sgmy|krjp|jp/.test(pack.id)) return 'chinese';
  if (/movies|classic|series|family|animation|kids|entertainment|comedy/.test(pack.id)) return 'cinema';
  if (/documentary|science|culture|education|cooking|travel|relax|weather|business|sports|auto|music|outdoor/.test(pack.id)) {
    return 'doc_sport';
  }
  return 'global';
}

export function resolvePublicLivePackUrl(pack: PublicLivePack, origin: string): string {
  return pack.urlOrPath.startsWith('/') ? `${origin.replace(/\/+$/, '')}${pack.urlOrPath}` : pack.urlOrPath;
}
